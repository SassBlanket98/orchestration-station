#!/usr/bin/env python3
"""Draw the masthead title (Forum, spaced capitals, transparent PNG) and write src/titleart.py.

Needs Pillow and the font file (OFL, https://github.com/google/fonts/tree/main/ofl/forum):
    python3 make_title.py /path/to/Cinzel.ttf
The result is committed; station shows it only on terminals that speak the kitty graphics protocol."""
from __future__ import annotations

import base64
import io
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

TEXT = "STATION"
THEMES = {"tech": (111, 179, 184), "tokyo": (122, 162, 247)}   # widgets._wd_THEMES BLUE, the accent
SIZE, WEIGHT, SPACING = 220, 0, 0.12   # WEIGHT 0: a static font (Forum); Cinzel is variable (600 = SemiBold)


def main(font_path: str) -> None:
    font = ImageFont.truetype(font_path, SIZE)
    if WEIGHT:
        font.set_variation_by_axes([WEIGHT])
    gap = int(SIZE * SPACING)
    boxes = [font.getbbox(ch) for ch in TEXT]
    width = sum(b[2] - b[0] for b in boxes) + gap * (len(TEXT) - 1)
    top, bottom = min(b[1] for b in boxes), max(b[3] for b in boxes)
    mask = Image.new("L", (width, bottom - top), 0)
    draw, x = ImageDraw.Draw(mask), 0
    for ch, b in zip(TEXT, boxes):
        draw.text((x - b[0], -top), ch, font=font, fill=255)
        x += b[2] - b[0] + gap
    pngs, size = {}, (0, 0)
    for theme, color in THEMES.items():
        img = Image.new("RGBA", mask.size, color + (0,))
        img.putalpha(mask)
        img = img.resize((img.width // 2, img.height // 2), Image.LANCZOS)
        buf = io.BytesIO()
        img.save(buf, "PNG", optimize=True)
        pngs[theme], size = base64.b64encode(buf.getvalue()).decode("ascii"), img.size
    body = "".join(f'    "{theme}": (\n' + "".join(f'        "{data[i:i + 100]}"\n' for i in range(0, len(data), 100)) + "    ),\n"
                   for theme, data in pngs.items())
    out = Path(__file__).parent / "src" / "titleart.py"
    out.write_text(
        '"""The masthead title as a PNG per theme (generated by make_title.py: do not edit)."""\n'
        "from __future__ import annotations\n\n"
        f"_ta_SIZE = ({size[0]}, {size[1]})   # pixels\n"
        "_ta_PNG_B64: dict[str, str] = {\n" + body + "}\n"
    )
    print(f"{size[0]}x{size[1]} -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
