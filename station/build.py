#!/usr/bin/env python3
"""Join src/*.py into one executable station. Sibling imports are dropped; stdlib imports are hoisted."""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).parent
ORDER = ["model", "procs_darwin", "procs", "labels", "registry", "native", "logparse", "gitstate", "openclaw", "codexread", "events", "collect", "demo", "widgets", "titleart", "usageview", "opsspark", "opstree", "opsgrid", "ccactions", "ccpane", "ccstrip", "ccrow", "cchint", "cclayout", "ccspawn", "cckeys", "tutorial", "openclawview", "workerview", "sessionview", "render", "webdata", "web", "app"]
SIBLING = re.compile(rf"^from ({'|'.join(ORDER)}) import ")
STDLIB = re.compile(r"^(import |from \S+ import )")


def main() -> None:
    imports: set[str] = set()
    body: list[str] = []
    for name in ORDER:
        lines = (ROOT / "src" / f"{name}.py").read_text(encoding="utf-8").split("\n")
        body.append(f"\n\n# {'─' * 20} {name} {'─' * 20}")
        it = iter(lines)
        for line in it:
            if not (STDLIB.match(line) or line.startswith("from __future__")):
                body.append(line)
                continue
            stmt = line.rstrip()
            while stmt.count("(") > stmt.count(")"):  # parenthesised import spread over lines
                stmt += " " + next(it).strip()
            if not (SIBLING.match(stmt) or stmt.startswith("from __future__")):
                imports.add(stmt)
    head = (ROOT / "src" / "header.txt").read_text(encoding="utf-8").rstrip()
    out = [head, "from __future__ import annotations", "", *sorted(imports), *body, ""]
    generated = "\n".join(out)
    target = ROOT / "station"
    target.write_text(generated, encoding="utf-8")
    target.chmod(0o755)
    print(f"wrote {target} ({len(out)} lines)")
    if (ROOT / "src" / "register.py").is_file():
        producer_imports: set[str] = set()
        producer_body: list[str] = []
        sibling = re.compile(r"^from (model|procs_darwin|procs|registry|register) import ")
        for name in ("model", "procs_darwin", "procs", "registry", "register"):
            source = iter((ROOT / "src" / f"{name}.py").read_text(encoding="utf-8").splitlines())
            for line in source:
                if not (STDLIB.match(line) or line.startswith("from __future__")):
                    producer_body.append(line)
                    continue
                stmt = line.rstrip()
                while stmt.count("(") > stmt.count(")"):
                    stmt += " " + next(source).strip()
                if not (sibling.match(stmt) or stmt.startswith("from __future__")):
                    producer_imports.add(stmt)
        producer = ROOT / "station-register"
        producer.write_text("\n".join(["#!/usr/bin/env python3", "# Generated by build.py; edit src/*.py.",
                                       "from __future__ import annotations", *sorted(producer_imports),
                                       *producer_body, ""]), encoding="utf-8")
        producer.chmod(0o755)
        print(f"wrote {producer}")


if __name__ == "__main__":
    main()
